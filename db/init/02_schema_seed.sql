-- 02：切到业务库建震例表并灌入历史样例
\connect seisnet

GRANT CONNECT ON DATABASE seisnet TO replicator;
GRANT USAGE, CREATE ON SCHEMA public TO replicator;

-- 震例表：震例号、UTC 发震时刻、经度、纬度、震级
-- REPLICA IDENTITY 默认走主键，wal2json 的 delete/oldkeys 可拿到震例号
CREATE TABLE IF NOT EXISTS public.quake (
    quake_no   TEXT PRIMARY KEY,
    origin_utc TIMESTAMPTZ NOT NULL,
    longitude  DOUBLE PRECISION NOT NULL,
    latitude   DOUBLE PRECISION NOT NULL,
    magnitude  DOUBLE PRECISION NOT NULL
);

ALTER TABLE public.quake OWNER TO replicator;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.quake TO replicator;

